
import numpy as np
from sklearn.cluster import KMeans

# Given data
X = np.array([
    [1.713, 1.586], [0.180, 1.786], [0.353, 1.240],
    [0.940, 1.566], [1.485, 0.759], [1.266, 1.106],
    [1.540, 0.419], [0.459, 1.799], [0.773, 0.186]
])

# K-Means with 3 clusters
kmeans = KMeans(n_clusters=3, random_state=42, n_init=10)
kmeans.fit(X)

# Display cluster assignments
print("Cluster Labels:")
print(kmeans.labels_ + 1)

# Display centroids
print("\nCentroids:")
print(kmeans.cluster_centers_)

# New case
new_data = np.array([[0.906, 0.606]])

# Predict cluster
cluster = kmeans.predict(new_data)

print("\nNew Case: VAR1=0.906, VAR2=0.606")
print("Predicted Cluster:", cluster[0] + 1)


























